// One-off: converts the original Bible Quiz questions and Bible Quote verses
// into supabase/migration-005-games-seed.sql.
//   node scripts/build-games-seed.mjs <quiz-questions.json> <quote-verses.ts>
// (Node 22+ can import the .ts file directly.)
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";

const [quizPath, versesPath] = process.argv.slice(2);
if (!quizPath || !versesPath) {
  console.error("usage: node scripts/build-games-seed.mjs <questions.json> <verses.ts>");
  process.exit(1);
}

const quiz = JSON.parse(readFileSync(quizPath, "utf8"));
const { VERSE_BANK } = await import(pathToFileURL(resolve(versesPath)).href);

const LEVELS = new Set(["easy", "medium", "hard", "expert"]);
const j = (obj) => `$j$${JSON.stringify(obj)}$j$::jsonb`;

const quizRows = quiz.map((x) => {
  const level = String(x.difficulty || "MEDIUM").toLowerCase();
  if (!LEVELS.has(level)) throw new Error(`bad difficulty on ${x.id}`);
  if (!Array.isArray(x.options) || x.options.length < 2) throw new Error(`bad options on ${x.id}`);
  if (!(x.correctOptionIndex >= 0 && x.correctOptionIndex < x.options.length)) {
    throw new Error(`bad answer index on ${x.id}`);
  }
  return `('quiz','${level}',${j({
    question: x.question,
    options: x.options,
    correctIndex: x.correctOptionIndex,
    reference: x.reference ?? "",
    explanation: x.explanation ?? "",
    testament: x.testament ?? "",
    caption: x.illustrationCaption ?? "",
  })})`;
});

const quoteRows = VERSE_BANK.map(
  (v) =>
    `('quote',null,${j({
      reference: v.reference,
      hint: v.hint,
      funFact: v.funFact,
      translations: v.translations,
    })})`,
);

const sql = `-- Seed content for the Bible games. Generated by scripts/build-games-seed.mjs.
-- Run AFTER migration-004-games.sql. Safe to re-run: each game is only
-- seeded while it has no questions yet.

insert into public.game_questions (game, difficulty, payload)
select * from (values
${quizRows.join(",\n")}
) as v(game, difficulty, payload)
where not exists (select 1 from public.game_questions where game = 'quiz');

insert into public.game_questions (game, difficulty, payload)
select * from (values
${quoteRows.join(",\n")}
) as v(game, difficulty, payload)
where not exists (select 1 from public.game_questions where game = 'quote');
`;
writeFileSync("supabase/migration-005-games-seed.sql", sql);
console.log(`quiz: ${quizRows.length}, quote: ${quoteRows.length}`);
